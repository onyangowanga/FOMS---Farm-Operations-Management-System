import test from "node:test";
import assert from "node:assert/strict";
import bcrypt from "bcryptjs";
import { prisma } from "../server/src/config/database.js";
import { fixture, base, request } from "./helpers.js";

test("admin editing, OTP expiry/single-use concurrency, forced password change and revocation", { skip: !base }, async () => {
  const f = fixture();
  try {
    assert.equal((await request("/admin/clients")).status, 401);
    const admin = await f.seed("FOMS_ADMIN");
    const owner = await f.seed();
    const outsider = await f.seed();
    const path = `/admin/clients/${owner.organizationId}`;
    const profile = { ownerId: owner.user.id, organizationName: "Edited client", name: "Edited owner", username: `edited-${f.suffix}`, email: `edited-${f.suffix}@example.test` };
    assert.equal((await request(path, "PATCH", profile, owner.cookie)).status, 403);
    assert.equal((await request(path, "PATCH", { ...profile, ownerId: outsider.user.id }, admin.cookie)).status, 404);
    assert.equal((await request(path, "PATCH", profile, admin.cookie)).status, 200);
    const clients = (await request("/admin/clients", "GET", undefined, admin.cookie)).body.data;
    assert.equal(clients.find((client) => client.id === owner.organizationId).name, profile.organizationName);
    assert.equal(clients.find((client) => client.id === owner.organizationId).memberships[0].user.username, profile.username);
    assert.equal((await request("/auth/me", "GET", undefined, owner.cookie)).status, 401);
    const login = await request("/auth/login", "POST", { username: profile.username, password: f.password });
    assert.equal(login.status, 200);
    const resetPath = `${path}/owners/${owner.user.id}/reset-password`;
    const reset = await request(resetPath, "POST", {}, admin.cookie);
    assert.equal(reset.status, 200);
    assert.ok(Math.abs(new Date(reset.body.data.expiresAt) - Date.now() - 86400000) < 10000);
    const user = await prisma.user.findUniqueOrThrow({ where: { id: owner.user.id } });
    assert.equal(await bcrypt.compare(reset.body.data.temporaryPassword, user.temporaryPasswordHash), true);
    assert.notEqual(reset.body.data.temporaryPassword, user.temporaryPasswordHash);
    assert.equal((await request("/auth/me", "GET", undefined, login.cookie)).status, 401);
    assert.equal((await request("/auth/refresh", "POST", {}, login.cookie)).status, 401);
    assert.equal((await request("/auth/login", "POST", { username: profile.username, password: f.password })).status, 401);
    await prisma.user.update({ where: { id: owner.user.id }, data: { temporaryPasswordExpiresAt: new Date(Date.now() - 1000) } });
    assert.equal((await request("/auth/login", "POST", { username: profile.username, password: reset.body.data.temporaryPassword })).status, 401);
    const fresh = await request(resetPath, "POST", {}, admin.cookie);
    const password = fresh.body.data.temporaryPassword;
    const parallel = await Promise.all([0, 1].map(() => request("/auth/login", "POST", { username: profile.username, password })));
    assert.deepEqual(parallel.map((item) => item.status).sort(), [200, 401]);
    const restricted = parallel.find((item) => item.status === 200);
    assert.equal(restricted.body.data.passwordChangeRequired, true);
    assert.ok(!restricted.cookie.match(/(?:^|; )refreshToken=([^;]*)/)?.[1]);
    assert.equal((await request("/auth/me", "GET", undefined, restricted.cookie)).body.data.passwordChangeRequired, true);
    for (const resource of ["/dashboard", "/farms", "/journal/selectors", "/team", "/admin/clients"]) assert.equal((await request(resource, "GET", undefined, restricted.cookie)).status, 403);
    assert.equal((await request("/auth/password", "POST", { password: "weak" }, restricted.cookie)).status, 400);
    assert.equal((await request("/auth/password", "POST", { password }, restricted.cookie)).status, 400);
    assert.equal((await request("/auth/password", "POST", { password: f.password }, restricted.cookie)).status, 400);
    assert.equal((await request("/auth/password", "POST", { password: "Changed!pass9" }, restricted.cookie)).status, 200);
    assert.equal((await request("/auth/me", "GET", undefined, restricted.cookie)).status, 401);
    assert.equal((await request("/auth/login", "POST", { username: profile.username, password })).status, 401);
    const finalLogin = await request("/auth/login", "POST", { username: profile.username, password: "Changed!pass9" });
    assert.equal(finalLogin.status, 200);
    assert.equal(finalLogin.body.data.passwordChangeRequired, false);
    assert.equal((await request("/dashboard", "GET", undefined, finalLogin.cookie)).status, 200);
    const finalUser = await prisma.user.findUniqueOrThrow({ where: { id: owner.user.id } });
    assert.equal(finalUser.mustChangePassword, false);
    assert.equal(finalUser.temporaryPasswordHash, null);
  } finally { await f.cleanup(); }
});
